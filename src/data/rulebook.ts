const normalize = (value: string) => value.trim().toLowerCase().replace(/\s+/g, ' ');

export const findRulebookEntry = (name: string): RulebookEntry | undefined => {
  const target = normalize(name);
  return RULEBOOK_ENTRIES.find(entry =>
    normalize(entry.title) === target ||
    entry.aliases?.some(alias => normalize(alias) === target)
  ) ?? (target.endsWith('dragon pung') ? RULEBOOK_ENTRIES.find(entry => entry.id === 'dragon-pung') : undefined);
};
